const LANG_KEY = "bol-hindi-lang";

function getLang() {
  const saved = storeGet(LANG_KEY);
  return saved === "ta" ? "ta" : "en";
}

function setLang(lang) {
  storeSet(LANG_KEY, lang === "ta" ? "ta" : "en");
  document.documentElement.lang = lang === "ta" ? "ta" : "en";
  applyI18n();
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang: getLang() } }));
}

function t(key) {
  const lang = getLang();
  return I18N[lang][key] || I18N.en[key] || key;
}

function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = t(key);
    if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
      el.placeholder = value;
    } else {
      el.textContent = value;
    }
  });

  document.querySelectorAll(".lang-toggle button").forEach((btn) => {
    const lang = btn.getAttribute("data-lang");
    btn.setAttribute("aria-pressed", lang === getLang() ? "true" : "false");
  });
}

function initI18n() {
  document.documentElement.lang = getLang() === "ta" ? "ta" : "en";

  document.querySelectorAll(".lang-toggle button").forEach((btn) => {
    btn.addEventListener("click", () => setLang(btn.getAttribute("data-lang")));
  });

  applyI18n();
}

document.addEventListener("DOMContentLoaded", initI18n);
